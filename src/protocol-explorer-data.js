/** @param {Partial<{no:number,time:string,src:string,dst:string,proto:string,info:string,size:string}>} p */
function pkt(p) {
  return {
    no: p.no ?? 0,
    time: p.time ?? '0.000s',
    src: p.src ?? '',
    dst: p.dst ?? '',
    proto: p.proto ?? '',
    info: p.info ?? '',
    size: p.size ?? '—',
  };
}


/** @param {Partial<{no:number,time:string,from:string,to:string,phase:string,info:string}>} e */
function ev(e) {
  return {
    no: e.no ?? 0,
    time: e.time ?? '',
    from: e.from ?? '',
    to: e.to ?? '',
    phase: e.phase ?? '',
    info: e.info ?? '',
  };
}

